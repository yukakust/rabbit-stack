def function(text,name):
 m=re.search(r'^(?:static )?int '+name+r'\([^;]*?\n\{',text,re.M|re.S);assert m,name
 at=m.end();depth=1
 while depth:
  if text[at]=='{':depth+=1
  elif text[at]=='}':depth-=1
  at+=1
 return text[m.start():at]
